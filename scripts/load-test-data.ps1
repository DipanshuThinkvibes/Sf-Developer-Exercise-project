param(
    [string]$OrgAlias = "DeveloperExerciseProject-ScratchOrg",
    [string]$DataFile = "data/test-data.json",
    [switch]$NoDeploy
)

$ErrorActionPreference = "Stop"

$root = Split-Path -Parent $PSScriptRoot
if (-not [System.IO.Path]::IsPathRooted($DataFile)) {
    $DataFile = Join-Path $root $DataFile
}

$data = Get-Content -LiteralPath $DataFile -Raw | ConvertFrom-Json

function Esc([string]$value) {
    if ($null -eq $value) { return "" }
    return $value.Replace("'", "''")
}

function ApexDate([string]$value) {
    $d = [datetime]::ParseExact($value, 'yyyy-MM-dd', [Globalization.CultureInfo]::InvariantCulture)
    return "Date.newInstance($($d.Year), $($d.Month), $($d.Day))"
}

function Num($value) {
    return [string]::Format([Globalization.CultureInfo]::InvariantCulture, "{0}", $value)
}

function Money($value) {
    $d = [decimal]$value
    return $d.ToString('0.00', [Globalization.CultureInfo]::InvariantCulture)
}

$lines = New-Object System.Collections.Generic.List[string]

$lines.Add("// Generated by scripts/load-test-data.ps1 from $([System.IO.Path]::GetFileName($DataFile)).")
$lines.Add("// Clears old TalentBridge test data, then loads the data in the repository file.")
$accountNames = ($data.Account | ForEach-Object { "'$(Esc $_.Name)'" }) -join ', '
$lines.Add("List<Account> existingAccounts = [SELECT Id FROM Account WHERE Name IN ($accountNames)];")
$lines.Add("delete [SELECT Id FROM Hiring__c];")
$lines.Add("delete [SELECT Id FROM Position__c];")
$lines.Add("delete [SELECT Id FROM Consultant__c];")
$lines.Add("delete [SELECT Id FROM Contact WHERE AccountId IN :existingAccounts];")
$lines.Add("delete existingAccounts;")
$lines.Add("")

$accountVars = @{}
$accountVarList = New-Object System.Collections.Generic.List[string]
for ($i = 0; $i -lt $data.Account.Count; $i++) {
    $a = $data.Account[$i]
    $var = "emp$i"
    $accountVars[$a.key] = $var
    $accountVarList.Add($var)
    $lines.Add("Account $var = new Account(Name = '$(Esc $a.Name)', Domain__c = '$(Esc $a.Domain__c)');")
}
$lines.Add("insert new List<Account>{ $($accountVarList -join ', ') };")
$lines.Add("")

$contactVars = @{}
$contactVarList = New-Object System.Collections.Generic.List[string]
for ($i = 0; $i -lt $data.Contact.Count; $i++) {
    $c = $data.Contact[$i]
    $var = "hr$i"
    $contactVars[$c.key] = $var
    $contactVarList.Add($var)
    $lines.Add("Contact $var = new Contact(FirstName = '$(Esc $c.FirstName)', LastName = '$(Esc $c.LastName)', Email = '$(Esc $c.Email)', AccountId = $($accountVars[$c.AccountId]).Id);")
}
$lines.Add("insert new List<Contact>{ $($contactVarList -join ', ') };")
for ($i = 0; $i -lt $data.Account.Count; $i++) {
    $a = $data.Account[$i]
    $lines.Add("$($accountVars[$a.key]).HR_Contact__c = $($contactVars[$a.HR_Contact__c]).Id;")
}
$lines.Add("update new List<Account>{ $($accountVarList -join ', ') };")
$lines.Add("")

$consultantVars = @{}
$consultantVarList = New-Object System.Collections.Generic.List[string]
for ($i = 0; $i -lt $data.Consultant__c.Count; $i++) {
    $c = $data.Consultant__c[$i]
    $var = "con$i"
    $consultantVars[$c.key] = $var
    $consultantVarList.Add($var)
    $married = if ($c.Married__c) { "true" } else { "false" }
    $lines.Add("Consultant__c $var = new Consultant__c(First_Name__c = '$(Esc $c.First_Name__c)', Last_Name__c = '$(Esc $c.Last_Name__c)', DOB__c = $(ApexDate $c.DOB__c), Gender__c = '$(Esc $c.Gender__c)', Email__c = '$(Esc $c.Email__c)', Married__c = $married, Education__c = '$(Esc $c.Education__c)');")
}
$lines.Add("insert new List<Consultant__c>{ $($consultantVarList -join ', ') };")
$lines.Add("")

$positionVars = @{}
$positionVarList = New-Object System.Collections.Generic.List[string]
for ($i = 0; $i -lt $data.Position__c.Count; $i++) {
    $p = $data.Position__c[$i]
    $var = "pos$i"
    $positionVars[$p.key] = $var
    $positionVarList.Add($var)
    $lines.Add("Position__c $var = new Position__c(Name = '$(Esc $p.Name)', Employer__c = $($accountVars[$p.Employer__c]).Id, Openings__c = $(Num $p.Openings__c), Status__c = '$(Esc $p.Status__c)', Hourly_Rate__c = $(Money $p.Hourly_Rate__c), Description__c = '$(Esc $p.Description__c)');")
}
$lines.Add("insert new List<Position__c>{ $($positionVarList -join ', ') };")
$lines.Add("")

$hiringVarList = New-Object System.Collections.Generic.List[string]
for ($i = 0; $i -lt $data.Hiring__c.Count; $i++) {
    $h = $data.Hiring__c[$i]
    $var = "hir$i"
    $hiringVarList.Add($var)
    $parts = @(
        "Employer__c = $($accountVars[$h.Employer__c]).Id",
        "Consultant__c = $($consultantVars[$h.Consultant__c]).Id",
        "Hire_Date__c = $(ApexDate $h.Hire_Date__c)"
    )
    if (-not [string]::IsNullOrEmpty($h.Position__c)) {
        $parts += "Position__c = $($positionVars[$h.Position__c]).Id"
    }
    $lines.Add("Hiring__c $var = new Hiring__c($($parts -join ', '));")
}
$lines.Add("insert new List<Hiring__c>{ $($hiringVarList -join ', ') };")
$lines.Add("")
$lines.Add("System.debug('Loaded ' + $($data.Account.Count) + ' employers, ' + $($data.Consultant__c.Count) + ' consultants, ' + $($data.Position__c.Count) + ' positions and ' + $($data.Hiring__c.Count) + ' hirings.');")

$sectionComments = [ordered]@{
    '^Account emp0 '         = '// 1. Employers (at least 3, one called "TV")'
    '^Contact hr0 '          = '// HR Contacts for each employer'
    '^Consultant__c con0 '   = '// 2. Consultants (10 consultants: 3+ last names starting with "S", one called John)'
    '^Position__c pos0 '     = '// 3. Positions (6 positions, one called "Software Engineer")'
    '^Hiring__c hir0 '       = '// 4. Hirings (8 hirings, some older than 90 days)'
}

$namedLines = New-Object System.Collections.Generic.List[string]
for ($i = 0; $i -lt $lines.Count; $i++) {
    $line = $lines[$i]
    if ($i -eq 0) {
        $namedLines.Add('// Generated from data/test-data.json')
        continue
    }
    foreach ($pattern in $sectionComments.Keys) {
        if ($line -match $pattern) {
            $namedLines.Add($sectionComments[$pattern])
            break
        }
    }
    $namedLines.Add($line)
    if ($line -match '^insert new List<Contact>\{') {
        $namedLines.Add('')
    }
}
$namedLines.Add('')

$apexFile = Join-Path $PSScriptRoot '.generated-test-data.apex'
$apexNamedFile = Join-Path $PSScriptRoot 'apex\load-test-data.apex'
Set-Content -LiteralPath $apexFile -Value ($lines -join "`r`n") -Encoding ASCII
Set-Content -LiteralPath $apexNamedFile -Value ($namedLines -join "`r`n") -Encoding ASCII

Write-Host "Generated $apexFile and $apexNamedFile"
if (-not $NoDeploy) {
    & sf apex run --file $apexFile --target-org $OrgAlias
    if ($LASTEXITCODE -ne 0) {
        throw "Test data load failed with exit code $LASTEXITCODE"
    }
    Write-Host "Test data loaded into $OrgAlias"
}
